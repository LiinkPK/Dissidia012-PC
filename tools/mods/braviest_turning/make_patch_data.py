#!/usr/bin/env python3
"""Writes what the mod changes in the game's memory image, as a C++ include: the words it patches in the executable's own
segments and the bytes of the segment it adds (the code cave, whose code is compiled in; its data is read as data).

    make_patch_data.py <game EBOOT (the unmodified ELF/BIN)> <mod EBOOT.BIN> <out .inc>
"""
import struct, sys

def segments(d):
    phoff = struct.unpack_from('<I', d, 0x1C)[0]
    n = struct.unpack_from('<H', d, 0x2C)[0]
    out = []
    for i in range(n):
        t, off, va, pa, fs, ms, fl, al = struct.unpack_from('<8I', d, phoff + i * 32)
        if t == 1: out.append((off, va, fs, ms))
    return out

def main():
    base = open(sys.argv[1], 'rb').read(); mod = open(sys.argv[2], 'rb').read()
    bs = segments(base); ms = segments(mod)
    words, caves = [], []
    for off, va, fs, mem in ms:
        inside = next((s for s in bs if s[1] == va), None)
        if inside is None:
            caves.append((va, mod[off:off + fs])); continue
        n = min(fs, inside[2])
        for i in range(0, n - 3, 4):
            a = struct.unpack_from('<I', base, inside[0] + i)[0]; b = struct.unpack_from('<I', mod, off + i)[0]
            if a != b: words.append((va + i, b))
    with open(sys.argv[3], 'w', newline='\n') as f:
        f.write('// Generated by tools/mods/braviest_turning/make_patch_data.py: what the Braviest Turning mod changes in memory.\n')
        f.write('static const struct { std::uint32_t address, word; } kModWords[] = {\n')
        for a, w in words: f.write('    {0x%08Xu, 0x%08Xu},\n' % (a, w))
        f.write('};\n')
        f.write('static const struct { std::uint32_t address; std::uint32_t size; const std::uint8_t *bytes; } kModSegments[] = {\n')
        for k, (va, data) in enumerate(caves): f.write('    {0x%08Xu, %du, kModSegment%d},\n' % (va, len(data), k))
        f.write('};\n')
    # the byte arrays go before the table that points at them
    body = open(sys.argv[3]).read()
    arrays = ''
    for k, (va, data) in enumerate(caves):
        arrays += 'static const std::uint8_t kModSegment%d[%d] = {\n' % (k, len(data))
        for i in range(0, len(data), 24): arrays += '    ' + ', '.join('0x%02X' % x for x in data[i:i + 24]) + ',\n'
        arrays += '};\n'
    head, rest = body.split('\n', 1)
    open(sys.argv[3], 'w', newline='\n').write(head + '\n' + arrays + rest)
    print(len(words), 'patched words,', len(caves), 'added segment(s):', [(hex(v), len(d)) for v, d in caves])

main()
