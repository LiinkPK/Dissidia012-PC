#!/usr/bin/env python3
"""Merges a code mod into the generated corpus as a switch.

Inputs: the baseline corpus directory (the game as it is, profiles/d012_pk/work/generated) and a corpus generated by
`psp_recomp <modded ELF> --auto <dir> 0x08804000 --dispatch-call 0x08872138`. For every unit whose generated code differs,
each differing run of lines becomes

    if (g_d012_mod_bt) { <the mod's lines> } else { <the game's lines> }

so the same build runs either, by one global read at start-up. Units the mod adds (its code cave) are copied in and
registered. Run again on merged units: they are left as they are. Usage:

    merge_units.py <baseline_dir> <mod_dir> [--dry-run] [--skip 0103,...]
"""
import difflib, re, shutil, sys
from pathlib import Path

FLAG = "g_d012_mod_bt"
LABEL = re.compile(r"^\s*(L_[0-9A-Fa-f]+|case\s+\d+u|default)\s*:")

def read(p):
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n").split("\n")

def merge_unit(base, mod):
    a, b = read(base), read(mod)
    out, notes = [], []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag == "equal":
            out.extend(a[i1:i2]); continue
        old, new = a[i1:i2], b[j1:j2]
        # labels and the entry switch must be the same in both sides, or the switch cannot be made here
        if any(LABEL.match(l) for l in old + new):
            changed = [l.strip() for l in old + new if LABEL.match(l)]
            notes.append(f"line {i1+1}: label in a changed run: {changed[:3]}")
            out.extend(old)  # keep the game's; reported
            continue
        out.append(f"    if ({FLAG}) {{")
        out.extend(new if new else ["    // (nothing)"])
        out.append("    } else {")
        out.extend(old if old else ["    // (nothing)"])
        out.append("    }")
    return out, notes

def main():
    args = [x for x in sys.argv[1:] if not x.startswith("--")]
    dry = "--dry-run" in sys.argv
    skip = set()
    for x in sys.argv:
        if x.startswith("--skip="): skip = set(x[7:].split(","))
    base_dir, mod_dir = Path(args[0]), Path(args[1])
    total = 0
    for mod in sorted(mod_dir.glob("generated_unit_*.cpp")):
        num = mod.stem.split("_")[-1]
        base = base_dir / mod.name
        if not base.exists():
            print(f"{mod.name}: new unit (code the mod adds)")
            if not dry: shutil.copyfile(mod, base)
            continue
        if num in skip: print(f"{mod.name}: skipped"); continue
        text = base.read_bytes().decode("utf-8")
        if FLAG in text: print(f"{mod.name}: already merged"); continue
        if (mod.read_bytes() == base.read_bytes()): continue
        out, notes = merge_unit(base, mod)
        n = sum(1 for l in out if l.strip() == f"if ({FLAG}) {{")
        print(f"{mod.name}: {n} switches" + ("" if not notes else f"  PROBLEMS: {notes}"))
        total += n
        if not dry and n:
            crlf = "\r\n" in text
            base.write_bytes(("\r\n" if crlf else "\n").join(out).encode("utf-8"))
    print("switches:", total)

if __name__ == "__main__":
    main()
